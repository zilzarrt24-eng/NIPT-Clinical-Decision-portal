"""
View 4: Interactive ML Screening Calculator
"""

from pathlib import Path
import streamlit as st
import pandas as pd
import numpy as np
import joblib

from src.models import get_candidate_features, sanitize_input_features


def load_model(aneuploidy: str, model_type: str):
    model_path = Path("models") / aneuploidy.lower() / f"model_{model_type.lower()}_pipeline.joblib"
    if model_path.exists():
        return joblib.load(model_path)
    return None


def render_view4(master_df: pd.DataFrame):
    st.header("4. ML Screening (Interactive Calculator)")
    st.markdown(
        """
        Evaluate single-sample screening risk across three model levels:
        - **Model A**: Conventional baseline `Z_run` cutoff
        - **Model B**: 6 Chromosome-Specific Z-Scores + RBF-SVM
        - **Model C**: 6 Z-Scores + 5 Clinical/Assay Features + RBF-SVM
        """
    )

    st.warning(
        "⚠️ **Clinical Terminology & Scope Standard:** "
        "The outputs generated by this module represent **model-estimated screening probabilities** and "
        "**experimental screening outputs** developed for comparative research. "
        "They are NOT medical diagnoses and do NOT replace formal cytogenetic testing (e.g., amniocentesis/CVS)."
    )

    aneuploidy = st.selectbox("Select Target Condition for Screening", ["T21", "T18", "T13"], key="screen_aneu")
    prefix = f"{aneuploidy}_"

    # Two Operation Modes: Existing Sample vs Manual Experimental Input
    mode = st.radio(
        "Select Screening Input Mode",
        ["Mode A: Existing Sample Mode (Lookup)", "Mode B: Manual Experimental Input Mode (Research Tool)"],
        index=0
    )

    sample_data = {}

    if "Mode A" in mode:
        st.subheader("Mode A: Existing Sample Lookup")
        sample_id = st.selectbox("Select Sample ID", master_df["Sample ID"].tolist())
        row = master_df[master_df["Sample ID"] == sample_id].iloc[0]

        # Extract features
        z_run_val = float(row[f"{prefix}Z_run"])
        true_target = int(row[f"{prefix}Target"])
        qc_status = str(row["QC"])

        # 6 Z-scores
        z_features = {
            f"{prefix}Z_baseline_vs_n": float(row[f"{prefix}Z_baseline_vs_n"]),
            f"{prefix}Z_baseline_vs_p": float(row[f"{prefix}Z_baseline_vs_p"]),
            f"{prefix}Z_chr_vs_n": float(row[f"{prefix}Z_chr_vs_n"]),
            f"{prefix}Z_chr_vs_p": float(row[f"{prefix}Z_chr_vs_p"]),
            f"{prefix}Z_sample_vs_n": float(row[f"{prefix}Z_sample_vs_n"]),
            f"{prefix}Z_sample_vs_p": float(row[f"{prefix}Z_sample_vs_p"])
        }
        # 5 Clinical features
        clinical_features = {
            "fetal": float(row["fetal"]),
            "age": int(row["age"]),
            "week": int(row["week"]),
            "reads": int(row["reads"]),
            "peak": float(row["peak"])
        }

        st.caption(f"Ground Truth Label in Dataset: **{'Trisomy Positive (1)' if true_target == 1 else 'Reference/Euploid (0)'}** | Library QC: **{qc_status}**")

    else:
        st.subheader("Mode B: Manual Experimental Input Mode")
        st.info(
            "🔬 **Manual Experimental Input Mode:** Enter hypothetical, laboratory, or external feature values to explore model behavior. "
            "This function is designed strictly for computational sensitivity analysis and academic research.\n\n"
            "⚠️ **Predictor-Only Notice:** The ground truth outcome label (euploid vs. trisomy) is **NOT** entered by the user. "
            "Model B and Model C compute screening probabilities autonomously from predictor measurements."
        )

        st.markdown(f"##### 1. Conventional Baseline & Clinical / Assay Quality Features ({aneuploidy})")
        col1, col2, col3 = st.columns(3)
        with col1:
            z_run_val = st.number_input("Conventional Z_run (for Model A)", value=1.5, step=0.1, help="Primary chromosome Z-score for baseline thresholding.")
            age_val = st.number_input("Maternal Age (years)", value=32, min_value=15, max_value=50, step=1, help="Cohort range: 17 to 48 (median 31).")
            week_val = st.number_input("Gestational Age (weeks)", value=16, min_value=8, max_value=40, step=1, help="Cohort range: 10 to 38 (median 16).")
        with col2:
            fetal_val = st.number_input("Fetal Fraction (%)", value=10.5, step=0.5, help="Placental cfDNA fraction. Cohort median: 10.6%.")
            reads_val = st.number_input("Mapped Sequencing Reads", value=3800000, step=100000, help="Total sequencing depth. Cohort median: 3.82M.")
            peak_val = st.number_input("Fragment Peak (bp)", value=149.0, step=0.5, help="Nucleosomal library fragment peak. Cohort median: 149.1 bp.")
        with col3:
            st.caption("ℹ️ **Assay Ranges:** Typical euploid samples exhibit fetal fraction > 4.0%, fragment peak ~149 bp, and mapped reads > 2.5M.")

        st.markdown(f"##### 2. Six Chromosome-Specific Dosage Z-Scores ({aneuploidy})")
        col_z1, col_z2, col_z3 = st.columns(3)
        with col_z1:
            z_base_n = st.number_input(f"{prefix}Z_baseline_vs_n", value=0.0, step=0.5, help="Baseline vs normal controls.")
            z_base_p = st.number_input(f"{prefix}Z_baseline_vs_p", value=-10.0, step=0.5, help="Baseline vs positive controls.")
        with col_z2:
            z_chr_n = st.number_input(f"{prefix}Z_chr_vs_n", value=1.5, step=0.5, help="Chromosome-normalized vs normal controls.")
            z_chr_p = st.number_input(f"{prefix}Z_chr_vs_p", value=-8.0, step=0.5, help="Chromosome-normalized vs positive controls.")
        with col_z3:
            z_samp_n = st.number_input(f"{prefix}Z_sample_vs_n", value=0.0, step=0.5, help="Sample-normalized vs normal controls.")
            z_samp_p = st.number_input(f"{prefix}Z_sample_vs_p", value=-10.0, step=0.5, help="Sample-normalized vs positive controls.")

        run_btn = st.button("⚡ Run Experimental Screening", type="primary", use_container_width=True)

        z_features = {
            f"{prefix}Z_baseline_vs_n": z_base_n,
            f"{prefix}Z_baseline_vs_p": z_base_p,
            f"{prefix}Z_chr_vs_n": z_chr_n,
            f"{prefix}Z_chr_vs_p": z_chr_p,
            f"{prefix}Z_sample_vs_n": z_samp_n,
            f"{prefix}Z_sample_vs_p": z_samp_p
        }
        clinical_features = {
            "fetal": fetal_val,
            "age": age_val,
            "week": week_val,
            "reads": reads_val,
            "peak": peak_val
        }

    # Evaluate Models
    st.subheader(f"Side-by-Side Screening Comparison ({aneuploidy})")

    # Load pipelines
    model_b = load_model(aneuploidy, "B")
    model_c = load_model(aneuploidy, "C")

    # Model A: Baseline
    col_a, col_b, col_c = st.columns(3)
    with col_a:
        st.markdown("#### Model A: Conventional Baseline")
        st.write(f"**Baseline Z_run:** `{z_run_val:.2f}`")
        call_a = "Screen Positive" if z_run_val >= 3.0 else "Screen Reference"
        st.metric("Experimental Screening Output", call_a)
        st.caption("Decision Rule: Conventional threshold at Z >= 3.0")

    # Model B: 6 Z-Scores SVM
    with col_b:
        st.markdown("#### Model B: 6 Z-Scores RBF-SVM")
        if model_b is not None:
            df_b = pd.DataFrame([z_features])
            prob_b = float(model_b.predict_proba(df_b)[0, 1])
            call_b = "Elevated Risk" if prob_b >= 0.5 else "Low Risk"
            st.metric("Model-Estimated Screening Probability", f"{prob_b*100:.2f}%")
            st.write(f"**Experimental Screening Output:** `{call_b}`")
            st.progress(min(1.0, max(0.0, prob_b)))
            st.caption("Features: 6 chromosome-specific Z-scores")
        else:
            st.warning("Model B pipeline not yet trained on disk. Run training first.")

    # Model C: Extended Multivariate SVM
    with col_c:
        st.markdown("#### Model C: Extended Multivariate")
        if model_c is not None:
            df_c = pd.DataFrame([{**z_features, **clinical_features}])
            df_c_clean = sanitize_input_features(df_c, list(df_c.columns))
            prob_c = float(model_c.predict_proba(df_c_clean)[0, 1])
            call_c = "Elevated Risk" if prob_c >= 0.5 else "Low Risk"
            st.metric("Model-Estimated Screening Probability", f"{prob_c*100:.2f}%")
            st.write(f"**Experimental Screening Output:** `{call_c}`")
            st.progress(min(1.0, max(0.0, prob_c)))
            st.caption("Features: 6 Z-scores + fetal, age, week, reads, peak")
        else:
            st.warning("Model C pipeline not yet trained on disk. Run training first.")
